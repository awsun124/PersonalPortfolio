const HobbyIllustration = ({ hobby }: { hobby: Hobby }) => {
  const scene = scenes[hobby];
  const nodes = [...new Set(scene.outlines.flatMap((points) => points.split(" ")))];

  return (
    <svg viewBox="0 0 350 280" fill="none" aria-hidden="true" focusable="false" className="computer-constellation w-full h-full p-3 sm:p-4">
      {hobby === "Soccer" && (
        <circle cx="174" cy="179" r="56" stroke="currentColor" strokeWidth="1.15" pathLength="1" className="constellation-line" style={{ "--delay": "1.15s" } as CSSProperties} />
      )}
      {[...scene.outlines, ...scene.details].map((points, index) => hobby === "Soccer" && index === 8 ? null : (
        <polyline
          key={points}
          points={points}
          stroke="currentColor"
          strokeWidth={index < scene.outlines.length ? 1.15 : 0.7}
          strokeLinecap="round"
          strokeLinejoin="round"
          pathLength="1"
          className="constellation-line"
          style={{ "--delay": `${0.35 + (index % 11) * 0.1}s` } as CSSProperties}
        />
      ))}
      {nodes.map((point, index) => {
        const [cx, cy] = point.split(",").map(Number);
        return (
          <g key={point} className="constellation-star" style={{ "--delay": `${(index % 13) * 0.06}s` } as CSSProperties}>
            <circle cx={cx} cy={cy} r="4.5" fill="currentColor" opacity="0.06" />
            <circle cx={cx} cy={cy} r="1.35" fill="currentColor" opacity="0.9" />
          </g>
        );
      })}
    </svg>
  );
};

